bool fillOplParameters(Instrument& inst) {
    std::string norm = normaliseName(inst.name);
    if (norm.empty()) {
        inst.flag = kDefaultPreset.flag;
        std::memcpy(inst.params.data(), kDefaultPreset.params, 28);
        return true;
    }

    for (const auto& p : kPresets) {
        if (norm.find(p.key) != std::string::npos) {
            inst.flag = p.flag;
            std::memcpy(inst.params.data(), p.params, 28);
            return true;
        }
    }

    // Default fallback FM preset
    inst.flag = kDefaultPreset.flag;
    std::memcpy(inst.params.data(), kDefaultPreset.params, 28);
    return true;
}

void enrichInstruments(std::vector<Instrument>& instruments) {
    for (auto& inst : instruments) {
        if (!inst.hasParams()) {
            fillOplParameters(inst);
        }
    }
}

