std::string normaliseName(const std::string& name) {
    std::string s;
    for (char c : name) {
        if (std::isalnum(static_cast<unsigned char>(c))) {
            s.push_back(char(std::tolower(static_cast<unsigned char>(c))));
        }
    }
    return s;
}

